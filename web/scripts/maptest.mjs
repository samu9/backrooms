// Interactive check of the full map: walk, open it, place marks, close it, look at the minimap.
import { chromium } from 'playwright';
import { readdirSync } from 'node:fs';
const root = process.env.HOME + '/.cache/ms-playwright';
const exe = readdirSync(root).filter((d) => /^chromium-\d+$/.test(d)).sort().map((d) => `${root}/${d}/chrome-linux64/chrome`).pop();
const b = await chromium.launch({ executablePath: exe, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 960, height: 540 } });
const errs = [];
p.on('console', (m) => (m.type() === 'error') && !m.text().includes('404') && errs.push(m.text()));
p.on('pageerror', (e) => errs.push(String(e)));
await p.goto('http://127.0.0.1:5190/?seed=7');
await p.waitForTimeout(1500);
await p.click('#menu');
await p.keyboard.down('KeyW');
await p.waitForTimeout(5000);
await p.keyboard.up('KeyW');
await p.keyboard.press('KeyM');
await p.waitForTimeout(500);
await p.mouse.click(560, 220);
await p.mouse.click(400, 330);
await p.mouse.click(700, 120);
await p.mouse.click(400, 330, { button: 'right' });
await p.mouse.click(440, 300);
await p.waitForTimeout(600);
await p.screenshot({ path: 'shots/map-full.png' });
await p.keyboard.press('KeyM');
await p.waitForTimeout(800);
await p.screenshot({ path: 'shots/map-mini.png' });
console.log(errs.length ? 'errors:\n' + errs.join('\n') : 'no errors');
await b.close();
